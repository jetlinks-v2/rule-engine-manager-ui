import assert from 'node:assert/strict'
import { assertSceneContract } from './contract.mjs'
/** 用真实页面创建规则；保存结果来自接口捕获，随后重新加载同一条记录。 */
export async function runCases({ page, host, check }) {
  const dialog = () => page.locator('.ant-modal:visible')
  const button = (name) => page.getByRole('button', { name, exact: true })
  const detail = () => page.locator('.detailed-scene-editor')
  await check('UI-01', '切换到详细配置并显示真实编辑器', async () => {
    await page.getByText('详细配置', { exact: true }).click()
    await detail().waitFor()
    assert.equal(await detail().locator('.detailed-scene-editor__name-field input').count(), 1)
  })
  await check('UI-02', '空场景保存校验阻止提交', async () => {
    await button('保存场景').click()
    await page.waitForTimeout(300)
    assert.equal(host.backend.state.saves.length, 0)
    await page.locator('.ant-form-item-explain-error').first().waitFor()
  })
  await detail().locator('.detailed-scene-editor__name-field input').fill('前端集成-手动延迟')
  await check('UI-03', '触发选择器取消不产生节点', async () => {
    await detail().locator('.detailed-scene-editor__trigger-add').click()
    await dialog().locator('.ant-modal-close').click()
    await page.waitForTimeout(300)
    assert.equal(await detail().locator('.detailed-scene-editor__trigger-add').count(), 1)
  })
  await check('UI-04', '手动触发和动作选择弹窗', async () => {
    await detail().locator('.detailed-scene-editor__trigger-add').click()
    await dialog().locator('.trigger-picker__card').filter({ hasText: '手动执行触发' }).click()
    await detail().locator('.actions-add-list__button').first().click()
    await dialog().locator('button').filter({ hasText: '延迟' }).last().click()
    await dialog().locator('input').first().fill('7')
    await dialog()
      .getByRole('button', { name: /确\s*定/ })
      .click()
    await page.waitForTimeout(300)
    assert.ok((await detail().innerText()).includes('7'))
  })
  await check('UI-05', '保存真实请求并导航列表', async () => {
    await button('保存场景').click()
    await page.waitForURL('**/#/list', { timeout: 20000 })
    assert.equal(host.backend.state.saves.length, 1)
    const rule = assertSceneContract(host.backend.state.saves[0])
    assert.equal(rule.trigger.type, 'manual')
    assert.deepEqual(rule.branches[0].when, [])
    assert.equal(rule.branches[0].then[0].parallel, false)
    assert.deepEqual(rule.branches[0].then[0].actions[0].delay, { time: 7, unit: 'seconds' })
    assert.equal(rule.options.editorMode, 'detail')
  })
  await check('UI-06', '列表使用已保存配置反显并禁用执行', async () => {
    await page.getByText('前端集成-手动延迟', { exact: true }).waitFor()
    assert.ok((await page.locator('body').innerText()).includes('7'))
    assert.equal(await page.getByRole('button', { name: /执行$/ }).isDisabled(), true)
    assert.equal(host.backend.state.requests.filter((r) => r.path.endsWith('/_execute')).length, 0)
  })
  await check('UI-07', '重新打开刚创建的场景回显配置', async () => {
    const saved = host.backend.state.saves.at(-1)
    await page.goto(host.url + '/#/editor/' + saved.id)
    await detail().waitFor()
    assert.equal(await detail().locator('.detailed-scene-editor__name-field input').inputValue(), saved.name)
    assert.ok((await detail().innerText()).includes('7'))
  })
  await check('UI-08', '修改名称保存后节点配置保持不变', async () => {
    const before = structuredClone(host.backend.state.saves.at(-1))
    await detail().locator('.detailed-scene-editor__name-field input').fill('前端集成-修改名称')
    await button('保存场景').click()
    await page.waitForURL('**/#/list')
    const after = host.backend.state.saves.at(-1)
    assert.equal(after.id, before.id)
    assert.deepEqual(after.trigger, before.trigger)
    assert.deepEqual(after.branches, before.branches)
  })
  await check('UI-09', '重新编辑动作取消不改变已确认的延迟', async () => {
    await page.goto(host.url + '/#/editor/' + host.backend.state.saves.at(-1).id)
    await detail().waitFor()
    await detail().locator('.scene-node-card').filter({ hasText: '延迟' }).locator('button').first().click()
    await dialog().locator('input').first().fill('99')
    await dialog()
      .getByRole('button', { name: /取\s*消/, exact: true })
      .click()
    await page.waitForTimeout(300)
    assert.ok((await detail().innerText()).includes('7'))
    assert.ok(!(await detail().innerText()).includes('99'))
  })

  await check('UI-10', '动作确认修改及保存失败后保留草稿并可重试', async () => {
    await detail().locator('.scene-node-card').filter({ hasText: '延迟' }).locator('button').first().click()
    await dialog().locator('input').first().fill('11')
    await dialog()
      .getByRole('button', { name: /确\s*定/ })
      .click()
    host.backend.state.failNextSave = true
    const count = host.backend.state.saves.length
    await button('保存场景').click()
    await page.waitForTimeout(500)
    assert.equal(host.backend.state.saves.length, count)
    assert.ok(await detail().isVisible())
    assert.ok((await detail().innerText()).includes('11'))
    await button('保存场景').click()
    await page.waitForURL('**/#/list')
    assert.equal(host.backend.state.saves.length, count + 1)
    assert.equal(host.backend.state.saves.at(-1).branches[0].then[0].actions[0].delay.time, 11)
  })
  await check('UI-11', '已配置规则切换模式取消后保留节点', async () => {
    await page.goto(host.url + '/#/editor/' + host.backend.state.saves.at(-1).id)
    await detail().waitFor()
    await page.getByText('快速配置', { exact: true }).click()
    await dialog()
      .getByRole('button', { name: /取\s*消/ })
      .click()
    await page.waitForTimeout(300)
    assert.ok(await detail().isVisible())
    assert.ok((await detail().innerText()).includes('11'))
  })
  await check('UI-12', '已配置规则确认切换模式会清空配置并保留名称', async () => {
    await page.getByText('快速配置', { exact: true }).click()
    await dialog().locator('.ant-btn-primary').click()
    await page.locator('.scene-editor').waitFor()
    assert.equal(await page.locator('.scene-editor__name').inputValue(), '前端集成-修改名称')
    assert.equal(await page.locator('.scene-node-card--action').count(), 0)
  })
  await page.goto(host.url + '/#/editor')
  await page.getByText('详细配置', { exact: true }).click()
  await detail().waitFor()
  await detail().locator('.detailed-scene-editor__name-field input').fill('前端集成-Cron')
  await check('UI-13', '新建定时触发取消不残留节点', async () => {
    await detail().locator('.detailed-scene-editor__trigger-add').click()
    await dialog().locator('.trigger-picker__card').filter({ hasText: '特定时间触发' }).click()
    await dialog()
      .getByRole('button', { name: /取\s*消/, exact: true })
      .click()
    await page.waitForTimeout(300)
    assert.equal(await detail().locator('.detailed-scene-editor__trigger-add').count(), 1)
  })
  await check('UI-14', 'Cron 非法格式阻止确认，合法格式可保存', async () => {
    await detail().locator('.detailed-scene-editor__trigger-add').click()
    await dialog().locator('.trigger-picker__card').filter({ hasText: '特定时间触发' }).click()
    await dialog().getByText('cron表达式', { exact: true }).click()
    await dialog().locator('input:not([type=radio])').first().fill('invalid')
    await dialog()
      .getByRole('button', { name: /确\s*定/ })
      .click()
    await dialog().locator('.ant-form-item-explain-error').first().waitFor()
    await dialog().locator('input:not([type=radio])').first().fill('0 0 8 * * ?')
    await dialog()
      .getByRole('button', { name: /确\s*定/ })
      .click()
    await detail().locator('.actions-add-list__button').first().click()
    await dialog().locator('.action-picker__item').filter({ hasText: '延迟' }).click()
    await dialog()
      .getByRole('button', { name: /确\s*定/ })
      .click()
    await button('保存场景').click()
    await page.waitForURL('**/#/list')
    const rule = assertSceneContract(host.backend.state.saves.at(-1))
    assert.deepEqual(rule.branches[0].when, [])
    assert.equal(rule.trigger.timer.cron, '0 0 8 * * ?')
    await page.goto(host.url + '/#/editor/' + rule.id)
    await detail().waitFor()
    assert.ok(
      (await detail().innerText()).includes('08:00') || (await detail().innerText()).includes('0 0 8'),
    )
  })
  await check('UI-15', '设备触发选择产品后展示设备与操作配置', async () => {
    await page.goto(host.url + '/#/editor')
    await page.getByText('详细配置', { exact: true }).click()
    await detail().locator('.detailed-scene-editor__trigger-add').click()
    await dialog().locator('.trigger-picker__card').filter({ hasText: '物联设备触发' }).click()
    await dialog().getByText('测试温控产品', { exact: true }).click()
    await dialog().getByRole('button', { name: '下一步', exact: true }).click()
    await dialog().locator('.device-scope-modal__device-table').waitFor()
    assert.equal(await dialog().getByText('按关系', { exact: true }).count(), 0)
  })
  await check('UI-16', '设备触发固定设备确认并显示节点', async () => {
    await dialog()
      .locator('.device-scope-modal__device-table tbody tr')
      .filter({ hasText: '测试温控产品设备1' })
      .click()
    await dialog()
      .getByRole('button', { name: /确\s*定/ })
      .click()
    await page.waitForTimeout(300)
    assert.ok((await detail().innerText()).includes('测试温控产品设备1'))
    assert.ok((await detail().innerText()).includes('设备1在线'))
  })
  await check('UI-17', '并行动作选择器隐藏延迟，取消无新增动作', async () => {
    await detail().locator('.ant-collapse-header').filter({ hasText: '并行' }).click()
    await detail()
      .locator('.ant-collapse-item')
      .filter({ hasText: '并行' })
      .locator('.actions-add-list__button')
      .click()
    assert.equal(await dialog().locator('.action-picker__item').filter({ hasText: '延迟' }).count(), 0)
    await dialog().locator('.ant-modal-close').click()
    await page.waitForTimeout(300)
    assert.equal(await detail().locator('.scene-node-card--action').count(), 0)
  })
  await check('UI-18', '设备指令打开统一设备配置弹窗', async () => {
    await detail().locator('.actions-add-list__button').first().click()
    await dialog().locator('.action-picker__item').filter({ hasText: '设备指令' }).click()
    await dialog().getByText('测试温控产品', { exact: true }).click()
    await dialog().getByRole('button', { name: '下一步', exact: true }).click()
    await dialog().locator('.device-scope-modal__device-table').waitFor()
    assert.equal(await dialog().getByText('按关系', { exact: true }).count(), 0)
    assert.ok(!(await dialog().innerText()).includes('触发规则'))
  })
  await check('UI-19', '设备指令按变量只显示同产品设备ID', async () => {
    await dialog().getByText('按变量', { exact: true }).click()
    assert.ok(!(await dialog().innerText()).includes('按关系'))
    assert.ok(!(await dialog().innerText()).includes('系统时间'))
    await dialog().locator('.ant-select').first().click()
    await page.locator('.ant-select-dropdown:visible').getByText('设备ID', { exact: true }).waitFor()
  })
  await check('UI-20', '设备变量范围与读取属性确认写入节点', async () => {
    await page.locator('.ant-select-dropdown:visible').getByText('设备ID', { exact: true }).click()
    await dialog().locator('.device-scope-modal__selection .ant-select').first().click()
    await page.locator('.ant-select-dropdown:visible').getByText('读取属性', { exact: true }).click()
    await dialog().locator('.device-scope-modal__selection .ant-select').last().click()
    await page.locator('.ant-select-dropdown:visible').getByText('温度', { exact: true }).click()
    await dialog()
      .getByRole('button', { name: /确\s*定/ })
      .click()
    await page.waitForTimeout(200)
    assert.ok((await detail().innerText()).includes('温度'))
  })
  await check('UI-21', '空条件阻止保存，删除条件取消和确认分别生效', async () => {
    await detail().locator('.detailed-scene-editor__name-field input').fill('前端集成-设备读取')
    const count = host.backend.state.saves.length
    await button('保存场景').click()
    await page.locator('.ant-form-item-explain-error').first().waitFor()
    assert.equal(host.backend.state.saves.length, count)
    await detail().locator('.terms-params-delete:visible').first().click()
    await dialog()
      .getByRole('button', { name: /Cancel|取\s*消/ })
      .click()
    assert.equal(await detail().locator('.terms-params-item').count(), 1)
    await detail().locator('.terms-params-delete:visible').first().click()
    await dialog()
      .getByRole('button', { name: /OK|确\s*定/ })
      .click()
    await page.waitForTimeout(200)
    assert.equal(await detail().locator('.terms-params-item').count(), 0)
  })
  await check('UI-22', '设备触发与按变量读取保存、列表和编辑往返', async () => {
    await button('保存场景').click()
    await page.waitForURL('**/#/list')
    const saved = assertSceneContract(host.backend.state.saves.at(-1))
    assert.equal(saved.trigger.device.productId, 'p-full')
    assert.equal(saved.trigger.device.selector, 'fixed')
    assert.ok(JSON.stringify(saved.trigger.device.selectorValues).includes('p-full-d1'))
    const action = saved.branches[0].then.flatMap((group) => group.actions)[0]
    assert.equal(action.executor, 'device')
    assert.equal(action.device.source, 'upper')
    assert.equal(action.device.upperKey, 'scene.deviceId')
    assert.equal(action.device.message.messageType, 'READ_PROPERTY')
    assert.deepEqual(action.device.message.properties, ['temperature'])
    await page.getByText('前端集成-设备读取', { exact: true }).waitFor()
    assert.ok((await page.locator('body').innerText()).includes('温度'))
    await page.goto(host.url + '/#/editor/' + saved.id)
    await detail().waitFor()
    await detail().locator('.scene-node-card--action button').first().click()
    await dialog().locator('.device-scope-modal__selection').waitFor()
    assert.ok((await dialog().innerText()).includes('温度'))
    assert.ok((await dialog().innerText()).includes('设备ID'))
    await dialog()
      .getByRole('button', { name: /取\s*消/ })
      .click()
    await button('保存场景').click()
    await page.waitForURL('**/#/list')
    assert.deepEqual(host.backend.state.saves.at(-1).trigger, saved.trigger)
    assert.deepEqual(host.backend.state.saves.at(-1).branches, saved.branches)
  })
  await check('UI-23', '空物模型设备触发只提供上线和离线', async () => {
    await page.goto(host.url + '/#/editor')
    await page.getByText('详细配置', { exact: true }).click()
    await detail().locator('.detailed-scene-editor__trigger-add').click()
    await dialog().locator('.trigger-picker__card').filter({ hasText: '物联设备触发' }).click()
    await dialog().getByText('空物模型产品', { exact: true }).click()
    await dialog().getByRole('button', { name: '下一步', exact: true }).click()
    await dialog().locator('.device-scope-modal__selection .ant-select').first().click()
    await page.locator('.ant-select-dropdown:visible .ant-select-item-option').first().waitFor()
    const options = await page
      .locator('.ant-select-dropdown:visible .ant-select-item-option')
      .allTextContents()
    assert.equal(options.length, 2)
    assert.ok(options.some((value) => value.includes('上线')))
    assert.ok(options.some((value) => value.includes('离线')))
    await page.locator('.ant-select-dropdown:visible .ant-select-item-option').first().click()
    await dialog()
      .getByRole('button', { name: /取\s*消/ })
      .click()
  })
  await check('UI-24', '只读产品隐藏写属性和功能指令', async () => {
    await page.goto(
      host.url + '/#/editor/' + host.backend.state.saves.find((rule) => rule.triggerType === 'device').id,
    )
    await detail().waitFor()
    await detail().locator('.actions-add-list__button').first().click()
    await dialog().locator('.action-picker__item').filter({ hasText: '设备指令' }).click()
    await dialog().getByText('只读产品', { exact: true }).click()
    await dialog().getByRole('button', { name: '下一步', exact: true }).click()
    await dialog().locator('.device-scope-modal__selection .ant-select').first().click()
    await page.locator('.ant-select-dropdown:visible .ant-select-item-option').first().waitFor()
    const options = await page
      .locator('.ant-select-dropdown:visible .ant-select-item-option')
      .allTextContents()
    assert.equal(options.length, 1)
    assert.ok(options[0].includes('读取属性'))
    await page.locator('.ant-select-dropdown:visible .ant-select-item-option').first().click()
    await dialog()
      .getByRole('button', { name: /取\s*消/ })
      .click()
  })
  await check('UI-25', '保存加载期间再次点击不会产生重复请求', async () => {
    host.backend.state.delayMs = 600
    const count = host.backend.state.saves.length
    const requests = () =>
      host.backend.state.requests.filter((item) => item.method === 'PUT' && item.path.startsWith('/scene/'))
        .length
    const before = requests()
    await button('保存场景').evaluate((element) => {
      element.click()
      element.click()
    })
    await page.waitForURL('**/#/list')
    host.backend.state.delayMs = 0
    assert.equal(requests() - before, 1)
    assert.equal(host.backend.state.saves.length, count + 1)
  })
  await check('UI-26', '重新添加条件并配置温度等于0', async () => {
    const saved = host.backend.state.saves.find((rule) => rule.triggerType === 'device')
    await page.goto(host.url + '/#/editor/' + saved.id)
    await detail().waitFor()
    await detail().locator('.scene-filter-add-button').first().click()
    await detail().locator('.terms-params-item .scene-select').first().click()
    await page.locator('.ant-dropdown:visible').getByText('温度', { exact: true }).click()
    await detail().locator('.terms-params-item .scene-select-value').first().click()
    await page.locator('.ant-dropdown:visible input').first().fill('0')
    await page.locator('.ant-dropdown:visible input').first().press('Tab')
    await detail().locator('.detailed-scene-editor__name-field input').click()
    await button('保存场景').click()
    await page.waitForURL('**/#/list')
    const rule = assertSceneContract(host.backend.state.saves.at(-1))
    const term = rule.branches[0].when[0].terms[0]
    assert.equal(term.column, 'properties.temperature')
    assert.equal(term.termType, 'eq')
    assert.equal(term.value.value, 0)
    await page.getByText(rule.name, { exact: true }).waitFor()
    assert.ok((await page.locator('body').innerText()).includes('温度'))
    await page.goto(host.url + '/#/editor/' + rule.id)
    await detail().locator('.terms-params-item').waitFor()
    assert.ok((await detail().innerText()).includes('温度'))
  })
  await check('UI-27', '初始化慢请求完成前不开放模式切换，返回后不会覆盖详细模式', async () => {
    let release
    const held = new Promise((resolve) => {
      release = resolve
    })
    const pattern = '**/__api/scene/trigger/supports'
    await page.route(pattern, async (route) => {
      await held
      await route.continue()
    })
    await page.goto(host.url + '/#/editor')
    await page.locator('.scene-editor__loading').waitFor()
    assert.equal(await page.getByText('详细配置', { exact: true }).count(), 0)
    release()
    await page.locator('.scene-editor').waitFor()
    await page.getByText('详细配置', { exact: true }).click()
    await detail().waitFor()
    await page.waitForTimeout(250)
    assert.ok(await detail().isVisible())
    await page.unroute(pattern)
  })
}
